## Визуальный стиль

**Цветовая палитра:**
- Основной: ярко-жёлтый #FFD700 / оранжевый — для фона плашек и акцентов
- Текст поверх жёлтого: чёрный, жирный
- Текст поверх фото: белый, с тенью
- Фон постов: преимущественно тёмный (чёрный/серый) — еда на нём «светится»

**Логотип:** Птица Hungry Bird — дружелюбный персонаж. Виден на сайте, в приложении, на упаковке.

**Настроение фото:** тёплое, аппетитное, яркое. Блюдо выглядит так, будто его только что приготовили. Пар, соус, текстура — видны.

**Композиция:**
- Предпочтительно: крупный план блюд (текстура, ингредиенты, соусы)
- Для атмосферы: общий план стола с несколькими блюдами
- Ракурс: сверху (flat lay) или под 45° (как гость за столом)
- Текстовые оверлеи: короткая фраза поверх фото, жёлтая/оранжевая плашка

**Что всегда в кадре:**
- Свежее блюдо (горячее, парящее, сочное)
- Фирменные цвета бренда (жёлтый/оранжевый акцент)
- Чистый фон — ничего лишнего, фокус на еде

**Что НЕ должно быть в кадре:**
- Мусор, грязная посуда, крошки
- Посторонние люди без спроса
- Холодная/заветренная еда
- Чужие бренды (напитки конкурентов в кадре)
- Мелкий текст — если оверлей, то 3–7 слов максимум
