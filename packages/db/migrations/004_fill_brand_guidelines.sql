**Цветовая палитра:**
- Основной: ярко-жёлтый / оранжевый (как на сайте в кнопках)
- Дополнительный: чёрный (текст, лого), белый (фон)
- Акцентный: красный (для акций и фокусов)

**Логотип:** Птица Hungry Bird — дружелюбный персонаж. Виден в шапке сайта и в приложении.

**Настроение фото:** тёплое, аппетитное. Еда на переднем плане, яркое освещение.

**Композиция:**
- Предпочтительно: крупный план блюд (видна текстура, ингредиенты)
- Для атмосферы: общий план стола с несколькими блюдами
- Ракурс: сверху (flat lay) или под 45° (как гость за столом)

