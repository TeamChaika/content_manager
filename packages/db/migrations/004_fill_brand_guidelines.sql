## Тон голоса (Tone of Voice)

**Обращение:** на «ты» — дружелюбно, как хороший знакомый

**Стиль:** энергичный, с юмором, живой. Короткие фразы. Мы — не ресторан, мы — друг, который знает, где вкусно поесть. Пишем так, как говорим в жизни.

**Фирменные приёмы:**
- Начинаем с эмодзи, задающего настроение (🍔🔥😍)
- Одна мысль = один пост. Не смешиваем 3 темы
- Цена — открыто, без стеснения. «Всего 680 ₽» — ок. «По карману каждому» — нет
- Call-to-action всегда в конце: «закажи», «попробуй», «жми ссылку»
- Описываем еду конкретно: не «сочный бургер», а «котлета из мраморной говядины, сыр чеддер, томлёный лук»

**Примеры хороших фраз:**
1. «🍔 Фирменный бургер — 680 ₽. Котлета из мраморной говядины, чеддер, томлёный лук и секретный соус. Доставка за час. Жми ⬇»
2. «😍 Пятница. Ты. И роллы Филадельфия. Совпадение? Не думаю.»
3. «🔥 Хит продаж этой недели — Камамбер и пряная груша. Да, груша в бургере. И да, это божественно. 750 ₽»

**Примеры плохих фраз (что НЕ пишем):**
1. «Успейте заказать, скидка сгорит!» — агрессивный дедлайн, фальшивая срочность
2. «Лучшая доставка Ялты!» — голословное хвастовство без доказательств
3. Длинные простыни на 2000+ знаков — никто не читает
4. «По карману каждому» — снисходительно
